class FakeGenerator:
    def __init__(self, responses: Optional[Dict[str, str]] = None):
        self.responses = responses or {}
        self.calls = []

    async def generate_code(
        self,
        model_id: str,
        provider_name: str,
        language: str,
        problem: str,
        previous_code: Optional[str] = None,
        feedback: Optional[str] = None,
        constraints: Optional[str] = "",
        sample_cases: Optional[List[Dict[str, str]]] = None,
    ) -> GenerationResult:
        self.calls.append({"model_id": model_id, "feedback": feedback})
        code = self.responses.get(model_id, f"// Code generated by {model_id}")
        return GenerationResult(
            code=code,
            cost_usd=0.0005 if "balanced" in model_id else (0.004 if "frontier" in model_id else 0.0001),
            latency_ms=150.0,
        )


class FakeVerifier:
    def __init__(self, outcomes: Optional[Dict[str, VerificationResult]] = None):
        self.outcomes = outcomes or {}
        self.calls = []

    async def verify_code(
        self,
        language: str,
        code: str,
        test_cases: List[Dict[str, str]],
        timeout_sec: float = 3.0,
    ) -> VerificationResult:
        self.calls.append({"code": code})
        # Default or outcome matching code
        for k, outcome in self.outcomes.items():
            if k in code:
                return outcome
        return VerificationResult(
            status="accepted",
            passed_tests=len(test_cases),
            total_tests=len(test_cases),
            execution_time_ms=10.0,
        )


class TestEscalationPolicy(unittest.TestCase):
    def setUp(self):
        self.policy = EscalationPolicy(max_attempts=3, max_cost_usd=0.05, max_latency_ms=30000)
        self.candidates = [
            {"model_id": "model-balanced", "avg_cost_per_attempt": 0.0005},
            {"model_id": "model-frontier", "avg_cost_per_attempt": 0.0040},
        ]

    def test_accepted_stops_pipeline(self):
        attempts = [
            AttemptRecord(
                attempt_number=1,
                model_id="model-balanced",
                provider_name="fake",
                code="print(42)",
                status="accepted",
                passed_tests=3,
                total_tests=3,
                cost_usd=0.0005,
                latency_ms=200.0,
            )
        ]
        decision = self.policy.evaluate(attempts, self.candidates)
        self.assertEqual(decision.action, EscalationAction.STOP_ACCEPTED)

    def test_compilation_error_triggers_same_model_retry(self):
        attempts = [
            AttemptRecord(
                attempt_number=1,
                model_id="model-balanced",
                provider_name="fake",
                code="syntax error",
                status="compilation_error",
                passed_tests=0,
                total_tests=3,
                cost_usd=0.0005,
                latency_ms=200.0,
                compiler_output="SyntaxError: invalid syntax",
            )
        ]
        decision = self.policy.evaluate(attempts, self.candidates)
        self.assertEqual(decision.action, EscalationAction.RETRY_SAME_MODEL)
        self.assertEqual(decision.target_model_id, "model-balanced")
        self.assertIn("SyntaxError", decision.repair_prompt_feedback)

    def test_wrong_answer_triggers_model_escalation(self):
        attempts = [
            AttemptRecord(
                attempt_number=1,
                model_id="model-balanced",
                provider_name="fake",
                code="print(0)",
                status="wrong_answer",
                passed_tests=1,
                total_tests=3,
                cost_usd=0.0005,
                latency_ms=200.0,
                diagnostics="Expected 10, got 0",
            )
        ]
        decision = self.policy.evaluate(attempts, self.candidates)
        self.assertEqual(decision.action, EscalationAction.ESCALATE_NEXT_MODEL)
        self.assertEqual(decision.target_model_id, "model-frontier")

    def test_max_attempts_exceeded_stops(self):
        attempts = [
            AttemptRecord(
                attempt_number=i,
                model_id=f"model-{i}",
                provider_name="fake",
                code="wrong",
                status="wrong_answer",
                passed_tests=0,
                total_tests=3,
                cost_usd=0.001,
                latency_ms=100.0,
            )
            for i in range(1, 4)
        ]
        decision = self.policy.evaluate(attempts, self.candidates)
        self.assertEqual(decision.action, EscalationAction.STOP_MAX_ATTEMPTS)

    def test_budget_exceeded_stops(self):
        policy = EscalationPolicy(max_attempts=5, max_cost_usd=0.002)
        attempts = [
            AttemptRecord(
                attempt_number=1,
                model_id="model-expensive",
                provider_name="fake",
                code="wrong",
                status="wrong_answer",
                passed_tests=0,
                total_tests=3,
                cost_usd=0.0025,
                latency_ms=100.0,
            )
        ]
        decision = policy.evaluate(attempts, self.candidates)
        self.assertEqual(decision.action, EscalationAction.STOP_BUDGET_EXCEEDED)


class TestRoutingEngineOrchestration(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.router = CodingRouter()
        # Patch profile manager inside router
        from app.analysis import model_profiles
        self.orig_profiles = model_profiles.coding_profile_manager.get_all_profiles
        model_profiles.coding_profile_manager.get_all_profiles = FakeProfiles().get_all_profiles

    async def asyncTearDown(self):
        from app.analysis import model_profiles
        model_profiles.coding_profile_manager.get_all_profiles = self.orig_profiles

    async def test_solve_first_attempt_accepted(self):
        gen = FakeGenerator()
        ver = FakeVerifier()
        engine = RoutingEngine(router=self.router, generator=gen, verifier=ver)

        req = SolveRequest(
            problem="Sum two numbers",
            algorithm_category="dynamic_programming",
            difficulty="easy",
            test_cases=[{"input": "1 2\n", "expected": "3\n"}],
        )

        resp: SolveResponse = await engine.solve(req)
        self.assertEqual(resp.status, "accepted")
        self.assertEqual(resp.total_attempts, 1)
        self.assertEqual(len(resp.attempts), 1)
        self.assertEqual(resp.passed_tests, 1)

    async def test_solve_escalates_on_wrong_answer(self):
        # Balanced fails on attempt 1, Frontier passes on attempt 2
        gen = FakeGenerator(responses={
            "model-balanced": "// balanced code",
            "model-frontier": "// frontier code",
        })
        ver = FakeVerifier(outcomes={
            "balanced code": VerificationResult(status="wrong_answer", passed_tests=0, total_tests=2, execution_time_ms=5.0),
            "frontier code": VerificationResult(status="accepted", passed_tests=2, total_tests=2, execution_time_ms=5.0),
        })

        engine = RoutingEngine(router=self.router, generator=gen, verifier=ver)

        req = SolveRequest(
            problem="Complex DP",
            algorithm_category="dynamic_programming",
            difficulty="hard",
            test_cases=[{"input": "1\n", "expected": "1\n"}, {"input": "2\n", "expected": "2\n"}],
        )

        resp: SolveResponse = await engine.solve(req)
        self.assertEqual(resp.status, "accepted")
        self.assertEqual(resp.total_attempts, 2)
        self.assertEqual(resp.initial_model, "model-balanced")
        self.assertEqual(resp.final_model, "model-frontier")
        self.assertIn("frontier code", resp.final_code)


